export const LANGUAGE_CODES = APP_LANGUAGES.map((l) => l.code);

export function isLanguage(value: string): value is Language {
  return (LANGUAGE_CODES as string[]).includes(value);
}

export function isRtlLanguage(code: Language): boolean {
  return APP_LANGUAGES.some((l) => l.code === code && l.rtl);
}

